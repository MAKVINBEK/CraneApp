// Максимальное количество недавних эмодзи
const MAX_RECENT = 50;

// Ключ для localStorage
const RECENT_KEY = 'craneapp_recent_emojis';

// ============================================
// ФУНКЦИИ
// ============================================

// Получить недавние эмодзи
function getRecentEmojis() {
    try {
        const stored = localStorage.getItem(RECENT_KEY);
        return stored ? JSON.parse(stored) : [];
    } catch (e) {
        return [];
    }
}

// Сохранить недавние эмодзи
function saveRecentEmojis(emojis) {
    try {
        localStorage.setItem(RECENT_KEY, JSON.stringify(emojis));
    } catch (e) {
        console.warn('Could not save recent emojis');
    }
}

// Добавить эмодзи в недавние
function addToRecent(emoji) {
    let recent = getRecentEmojis();
    
    // Удаляем если уже есть
    recent = recent.filter(e => e !== emoji);
    
    // Добавляем в начало
    recent.unshift(emoji);
    
    // Ограничиваем количество
    if (recent.length > MAX_RECENT) {
        recent = recent.slice(0, MAX_RECENT);
    }
    
    saveRecentEmojis(recent);
    EmojiData.recent = recent;
}

// Инициализация
function initEmojis() {
    EmojiData.recent = getRecentEmojis();
}

// Экспорт
if (typeof window !== 'undefined') {
    window.EmojiData = EmojiData;
    window.EmojiCategories = EmojiCategories;
    window.getRecentEmojis = getRecentEmojis;
    window.addToRecent = addToRecent;
    window.initEmojis = initEmojis;
    
    // Инициализация при загрузке
    initEmojis();
}

// Совместимость с браузером и Node.js
if (typeof module !== 'undefined' && module.exports) {
    module.exports = { EmojiData, EmojiCategories, getRecentEmojis, addToRecent, initEmojis };
}